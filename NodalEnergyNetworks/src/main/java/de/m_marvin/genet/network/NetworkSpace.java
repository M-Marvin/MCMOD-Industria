/**
 * A network space acts as an container for networks which are generated by adding elements and nodes to it.
 * It holds all data about the networks, nodes and elements being added to it and performs the 
 * necessary network rebuilding operations when elements are removed or added.
 * @param <N> The type used as node identifier/name
 * @param <E> The type used as element identifier/name
 * @param <Ei> The type of the element instances
 * @param <Ni> The type of the network instances
 */
public abstract class NetworkSpace<N, E, Ei extends NetworkElement<N, E, Ni>, Ni extends NetworkSpace<N, E, Ei, Ni>.Network> implements NetworkAccessor<N, E, Ei, Ni> {
	
	// reference to id mappings
	protected final BiMap<N, Integer> node2idn = UniMap.HASH_FAST.newBiMap();
	protected final BiMap<E, Integer> element2ide = UniMap.HASH_FAST.newBiMap();
	
	protected int lastNodeId = 0;
	protected int lastElementId = 0;
	
	// network space wide element and network mappings
	protected final MultiBiMap<Integer, Integer> idn2ide = UniMap.HASH_FAST.newMultiBiMap();
	protected final Int2ObjectMap<Ei> ide2instance = new Int2ObjectOpenHashMap<>();
	protected final BiMap<Integer, Ni> ide2network = new ModularBiMap<Integer, Ni>(new HashMap<Integer, Ni>(), new ModularMultiMap<Ni, Integer>(new IdentityHashMap<Ni, Set<Integer>>(), HashSet::new));
	
	/**
	 * This method is called if a new network needs to be constructed.
	 * The algorithms try to reuse existing instances as much as possible, but if networks are split new ones need to be constructed.
	 * @param elements The elements the network should be constructed with
	 * @return The new network instance with the elements already added
	 */
	protected abstract Ni createNetwork(IntCollection elements);
	
	protected final static int supplyFreeId(int lastId, Predicate<Integer> usedCheck) {
		int free = lastId;
		while (usedCheck.test(free)) {
			free++;
			if (free == lastId)
				throw new OutOfIdError("network out of element ids"); // will this ever happen ? I hope not ...
		}
		return free;
	}
	
	protected final int insertElementRef(E element) {
		Integer id = this.element2ide.get(element);
		if (id == null)
			this.element2ide.put(element, (id = supplyFreeId(this.lastElementId, this.element2ide::containsValue)));
		return id;
	}

	protected final int insertNodeRef(N node) {
		Integer id = this.node2idn.get(node);
		if (id == null)
			this.node2idn.put(node, (id = supplyFreeId(this.lastNodeId, this.node2idn::containsValue)));
		return id;
	}
	
	/**
	 * Directly performs an removal operation for the list of elements, followed by an rebuilding of the affected networks.<br>
	 * <b>Do not call this if you are not 100% sure you know what you are doing, {@link NetworkSpace#removeElements(Collection)} is most likely what you need</b>
	 * @param names The names of the elements to remove
	 * @return The list of instances which where removed
	 */
	public final Collection<Ei> directRemoveElements(Collection<E> names) {

		// remove elements from the network space to free up id space and collect idn and ide values
		Set<Ei> removed = new HashSet<Ei>();
		List<Pair<Collection<Integer>, Integer>> idnsAndIde = names.stream()
			.map(this.element2ide::remove)
			.filter(Objects::nonNull)
			.peek(ide -> removed.add(this.ide2instance.remove(ide.intValue())))
			.map(ide -> new Pair<>(this.idn2ide.removeValues(ide), ide))
			.toList();
		
		// remove element to network mappings and collect networks to split
		Collection<Ni> networksToSplit = idnsAndIde.stream()
			.map(pair -> this.ide2network.remove(pair.second()))
			.filter(Objects::nonNull)
			.distinct()
			.toList();
		
		// collect list of nodes to try splitting
		IntList nodesToSplit = IntArrayList.toList(idnsAndIde.stream()
				.flatMapToInt(pair -> pair.first().stream().mapToInt(Integer::intValue))
				.distinct());
		
		// remove unused idn values to free up id space
		nodesToSplit.intStream()
			.filter(idn -> this.idn2ide.getAll(idn).isEmpty())
			.forEach(this.node2idn::removeValue);
		
		// call the network remove event on the removed devices, since they will not be called by the network
		removed.forEach(NetworkElement::onRemovalFromNetwork);
		
		// split networks and update ide to network mappings
		networksToSplit.stream()
			.flatMap(network -> network.split(nodesToSplit).stream())
			.forEach(network -> network.elements.forEach(ide -> this.ide2network.put(ide, network)));
		
		return removed;
		
	}

	/**
	 * Directly performs an insertion operation for the list of elements, followed by an rebuilding of the affected networks.<br>
	 * <b>Do not call this if you are not 100% sure you know what you are doing, {@link NetworkSpace#insertElements(Collection)} is most likely what you need</b><br><br>
	 * <b>WARNING: This function assumes elements with identical names have been removed before, inserting an element with an duplicate name will cause a exception to be thrown</b>
	 * @param names The element instances to insert
	 */
	public final void directInsertElements(Collection<Ei> elements) {
		
		// register elements in the network space and collect ide values
		List<Integer> idns = elements.stream()
			.flatMap(instance -> {
				
				// register element reference in network space
				int ide = insertElementRef(instance.name());

				// register element nodes in network space
				Stream<Integer> idns2 = Stream.of(instance.nodes())
						.map(this::insertNodeRef)
						.peek(idn -> this.idn2ide.put(idn, ide));
				
				// update reference to instance mapping in network space
				if (this.ide2instance.put(ide, instance) != null)
					throw new IllegalStateException("illegal element insertion, conflicting elements: " + instance.name() + " as ide:" + ide);
				// NOTE: this code assumes a previous conflicting element to be already removed by the synchronizer code
				
				return idns2;
				
			}).distinct().toList();
		
		// trace connected elements and merge networks
		for (IntSet traceIdes : Tracer.traceFromNodes(this.idn2ide, idns)) {
			
			// find networks contained within the trace, and separate elements without any network
			Set<Ni> networksToMerge = new HashSet<Ni>();
			IntList netlessIdes = IntArrayList.toList(traceIdes.intStream()
				.filter(ide -> {
					Ni network = this.ide2network.get(ide);
					if (network != null) {
						networksToMerge.add(network);
						return false;
					}
					return true;
				}));
			
			// merge networks and add new elements
			Optional<Ni> network = networksToMerge.stream().max((n1, n2) -> Integer.compare(n1.elements.size(), n2.elements.size()));
			if (network.isPresent())
				network.get().merge(networksToMerge.stream().filter(n -> n != network.get()).toList(), netlessIdes);
			Ni mergedNetwork = network.orElseGet(() -> {
				// if there was no networks to merge (all new elements), create new network ...
				Ni newNetwork = createNetwork(netlessIdes);
				// ... and perform required operations on potential inner network
				newNetwork.finalizeSubSpace(FinalizationPhase.INSERTIONS);
				return newNetwork;
			});
			
			// update element network mappings
			mergedNetwork.elements.forEach(ide -> this.ide2network.put(ide, mergedNetwork));
			
		}
		
	}
	
	private final Set<Ei> insertionQueue = new LinkedHashSet<Ei>();
	private final Set<E> removalQueue = new LinkedHashSet<E>();
	
	/**
	 * Queues an list of elements for insertion into the networks of this network space.
	 * @param elements The element instances to insert
	 */
	public final void insertElements(Collection<Ei> elements) {
		this.insertionQueue.addAll(elements);
	}

	/**
	 * Queues an list of elements for insertion into the networks of this network space.
	 * @param elements The element instances to insert
	 */
	@SafeVarargs
	public final void insertElements(Ei... elements) {
		insertElements(Arrays.asList(elements));
	}

	/**
	 * Queues an list of elements for removal from the networks of this network space.
	 * @param names The element names to remove
	 */
	public final void removeElements(Collection<E> names) {
		this.removalQueue.addAll(names);
	}

	/**
	 * Queues an list of elements for removal from the networks of this network space.
	 * @param names The element names to remove
	 */
	@SafeVarargs
	public final void removeElements(E... names) {
		removeElements(Arrays.asList(names));
	}

	public static enum FinalizationPhase {
		REMOVALS,INSERTIONS;
	}
	
	/**
	 * This method needs to be called periodically to apply queued changes made by the {@link NetworkSpace#insertElements(Collection)} and {@link NetworkSpace#removeElements(Collection)} methods.<br>
	 * It is fine to call it in between calls to these function to process all requests queued up to that point, but ideally this function should be called every tick my some central event handler to guarantee synronized processing of all requests once every tick.<br><br>
	 * This method will first process the removal requests, then the insertion requests.
	 */
	public void finalizeQueuedChanges() {
		finalizeQueuedChanges(FinalizationPhase.REMOVALS);
		finalizeQueuedChanges(FinalizationPhase.INSERTIONS);
	}
	
	/**
	 * This method needs to be called periodically to apply queued changes made by the {@link NetworkSpace#insertElements(Collection)} and {@link NetworkSpace#removeElements(Collection)} methods.<br>
	 * It is fine to call it in between calls to these function to process all requests queued up to that point, but ideally this function should be called every tick my some central event handler to guarantee synronized processing of all requests once every tick.
	 * @param phase Weather to process the removal or insertion requests
	 */
	public void finalizeQueuedChanges(FinalizationPhase phase) {
		
		if (phase == FinalizationPhase.REMOVALS && (!this.removalQueue.isEmpty() || !this.insertionQueue.isEmpty())) {

			// check for conflicting elements which have to be removed before insertion
			Stream<E> removeForReplace = this.insertionQueue.stream()
				.map(Ei::name)
				.filter(name -> !this.removalQueue.contains(name))
				.filter(this.element2ide::containsKey);
			
			// build list of elements to remove
			Collection<E> toRemove = Stream.concat(removeForReplace, this.removalQueue.stream()).toList();
			
//			NodeNet.LOGGER.info(">>>> Network Space Finalization : REMOVAL : {} <<<<", this.toString());
//			NodeNet.LOGGER.info("Queued: {}", this.removalQueue);
//			NodeNet.LOGGER.info("Total: {}", toRemove);

			try {
				
				// remove elements
				directRemoveElements(toRemove);
				
			} catch (Exception e) {
				NodeNet.LOGGER.warn("unabel to finalize queued removals on network space, network might be persistently corrupted: {}", this, e);
			}

			// clear queue
			this.removalQueue.clear();

//			NodeNet.LOGGER.info(">>>> STATUS : {} <<<<", this.toString());
			
		} else if (phase == FinalizationPhase.INSERTIONS && !this.insertionQueue.isEmpty()) {

//			NodeNet.LOGGER.info(">>>> Network Space Finalization : INSERTION : {} <<<<", this.toString());
//			NodeNet.LOGGER.info("Queued: {}", this.insertionQueue);

			try {
				
				// insert elements
				directInsertElements(this.insertionQueue);
				
			} catch (Exception e) {
				NodeNet.LOGGER.warn("unabel to finalize queued insertions on network space, network might be persistently corrupted: {}", this, e);
			}

			// clear queue
			this.insertionQueue.clear();

//			NodeNet.LOGGER.info(">>>> STATUS : {} <<<<", this.toString());
			
		}
		
	}
	
	@Override
	public String toString() {
		return this.getClass().getSimpleName() + this.ide2network.values().stream().distinct().toList();
	}
	
	/**
	 * The base class of all network instances which can be held by a network space.<br>
	 * The base class implements the core functionality and utility methods used to work with networks and the underlying network space.
	 */
	public abstract class Network implements NetworkAccessor<N, E, Ei, Ni> {
		
		protected final IntSet elements = new IntOpenHashSet();
		
		public Network() {}
		
		/**
		 * Called after element instances have been removed from this network and after their event methods have been executed.
		 * @param elements The element instances which where removed from this network
		 */
		protected abstract void afterElementsAdded(Collection<Ei> elements);
		
		/**
		 * Called after element instances have been inserted to this network and after their event methods have been executed.
		 * @param elements The element instances which where inserted to this network
		 */
		protected abstract void afterElementsRemoved(Collection<Ei> elements);
		
		/**
		 * Called whenever changes to the network where made and inner network spaces might need to be notified to run their {@link NetworkSpace#finalizeQueuedChanges(FinalizationPhase)} routine.
		 * @param phase The finalization phase required to run
		 */
		protected abstract void finalizeSubSpace(FinalizationPhase phase);
		
		/**
		 * Directly inserts a new element to this network by its network space wide unique IDE (IDentification of Element)<br>
		 * <b>This method should never be called outside of the network space base class and the network constructor.</b><br>
		 * This method does not perform any network rebuilding and if called improperly, will cause persistent corruption of the network space data.
		 * @param elements The IDEs to insert
		 */
		@SuppressWarnings("unchecked")
		protected final void insertElements(IntCollection elements) {
			Collection<Ei> instances = elements.intStream()
				.mapToObj(ide -> new Pair<>(ide, NetworkSpace.this.ide2instance.get(ide)))
				.filter(pair -> pair.second() != null)
				.peek(pair -> this.elements.add(pair.first().intValue()))
				.peek(pair -> {
					try {
						pair.second().onInsertionToNetwork((Ni) this);
					} catch (Exception e) {
						NodeNet.LOGGER.warn("exception while inserting element to network: {} as ide:{}", pair.second().name(), pair.first(), e);
					}
				})
				.map(Pair::second)
				.toList();
			afterElementsAdded(instances);
		}

		/**
		 * Directly removes a new element from this network by its network space wide unique IDE (IDentification of Element)<br>
		 * <b>This method should never be called outside of the network space base class.</b><br>
		 * This method does not perform any network rebuilding and if called improperly, will cause persistent corruption of the network space data.
		 * @param elements The IDEs to remove
		 */
		protected final void removeElements(IntCollection element) {
			Collection<Ei> instances = element.intStream()
				.peek(this.elements::remove)
				.mapToObj(ide -> new Pair<>(ide, NetworkSpace.this.ide2instance.get(ide)))
				.filter(pair -> pair.second() != null)
				.peek(pair -> {
					try {
						pair.second().onRemovalFromNetwork();
					} catch (Exception e) {
						NodeNet.LOGGER.warn("exception while removing element from network: {} as ide:{}", pair.second().name(), pair.first(), e);
					}
				})
				.map(Pair::second)
				.toList();
			afterElementsRemoved(instances);
		}
		
		protected final void merge(Collection<Ni> networks, IntCollection elements) {
			IntStream insertions = IntStream.concat(
				networks.stream()
					.flatMapToInt(network -> {
						// remove the elements from the network ...
						IntList ides = IntArrayList.toList(network.getElements());
						network.removeElements(ides);
						// ... and perform the requred changes on the potential inner network space (to free the inner elements up for re-insertion)
						network.finalizeSubSpace(FinalizationPhase.REMOVALS);
						return ides.intStream();
					})
					.distinct(),
				elements.intStream()
			).distinct();
			// insert all elements to this network ...
			insertElements(IntArrayList.toList(insertions));
			// ... and perform the required changes here as well
			finalizeSubSpace(FinalizationPhase.INSERTIONS);
		}
		
		@SuppressWarnings({ "unchecked" })
		protected final Collection<Ni> split(Collection<Integer> startNodes) {
			List<IntSet> traces = Tracer.traceFromElements(NetworkSpace.this.idn2ide, this.elements, startNodes).stream()
				.sorted(ComparatorExtras.inverse(ComparatorExtras.toInt(IntSet::size)))
				.toList();
			
			// nothing to do here, the entire network will be discarded (it contains no relevant elements)
			if (traces.isEmpty()) {
				// run this anyway, this might mean all elements have been removed (and thus are still waiting to be processed)
				finalizeSubSpace(FinalizationPhase.REMOVALS);

				this.elements.clear();
				return Collections.emptyList();
			}
			
			Stream<Ni> newNetworks = StreamExtras.forFirst(traces.stream(), elements -> {
				// for the first resulting network, reuse this, remove everything which moved to another network ...
				removeElements(IntArrayList.toList(this.elements.intStream().filter(i -> !elements.contains(i))));
				// ... and perform the required operations on the potential inner network space (to free up the inner elements for re-insertion)
				finalizeSubSpace(FinalizationPhase.REMOVALS);
			// create new networks for the other elements (and perform the required insertion changes there as well)
			}).map(NetworkSpace.this::createNetwork).peek(network -> network.finalizeSubSpace(FinalizationPhase.INSERTIONS));
			
			// return this and the new networks as a result
			return Stream.concat(Stream.of((Ni) this), newNetworks).toList();
			
		}
		
		@Override
		public String toString() {
			return this.getClass().getSimpleName() + this.elements.toString();
		}
		
		/* >>>>>> Utility Methods <<<<<< */
		
		@Override
		public IntStream getNodes() {
			return this.elements.intStream()
					.mapToObj(NetworkSpace.this.idn2ide::getKeys)
					.flatMap(Collection::stream)
					.distinct()
					.mapToInt(Integer::intValue);
		}
		
		@Override
		public IntStream getElements() {
			return this.elements.intStream();
		}
		
		@Override
		public N getNodeName(Integer idn) {
			return NetworkSpace.this.getNodeName(idn);
		}
		
		@Override
		public E getElementName(Integer ide) {
			return NetworkSpace.this.getElementName(ide);
		}

		@Override
		public Ei getElementInstance(Integer ide) {
			return NetworkSpace.this.getElementInstance(ide);
		}

		@Override
		public Stream<E> getElementNames() {
			return getElements().mapToObj(this::getElementName);
		}

		@Override
		public Stream<Ei> getElementInstances() {
			return getElements().mapToObj(this::getElementInstance);
		}

		@Override
		public Stream<N> getNodeNames() {
			return getNodes().mapToObj(this::getNodeName);
		}
		
		@Override
		public IntStream getElementNodes(Integer ide) {
			return NetworkSpace.this.getElementNodes(ide);
		}

		@Override
		public Stream<N> getElementNodeNames(Integer ide) {
			return NetworkSpace.this.getElementNodeNames(ide);
		}

		@Override
		public IntStream getNodeElements(Integer idn) {
			return NetworkSpace.this.getNodeElements(idn);
		}

		@Override
		public Stream<E> getNodeElementNames(Integer idn) {
			return NetworkSpace.this.getNodeElementNames(idn);
		}

		@Override
		public Stream<Ei> getNodeElementInstances(Integer idn) {
			return NetworkSpace.this.getNodeElementInstances(idn);
		}
		
		@Override
		public Integer getNodeId(N nodeName) {
			return NetworkSpace.this.getNodeId(nodeName);
		}
		
		@Override
		public Integer getElementId(E elementName) {
			return NetworkSpace.this.getElementId(elementName);
		}
		
	}
	
	@Override
	public IntStream getNodes() {
		return this.node2idn.values().stream().mapToInt(Integer::intValue);
	}
	
	@Override
	public IntStream getElements() {
		return this.element2ide.values().stream().mapToInt(Integer::intValue);
	}
	
	@Override
	public N getNodeName(Integer idn) {
		return idn == null ? null : this.node2idn.getKey(idn);
	}
	
	@Override
	public E getElementName(Integer ide) {
		return ide == null ? null : this.element2ide.getKey(ide);
	}

	@Override
	public Ei getElementInstance(Integer ide) {
		return ide == null ? null : this.ide2instance.get(ide.intValue());
	}

	@Override
	public Stream<E> getElementNames() {
		return this.element2ide.keySet().stream();
	}
	
	@Override
	public Stream<Ei> getElementInstances() {
		return this.ide2instance.values().stream();
	}
	
	@Override
	public Stream<N> getNodeNames() {
		return this.node2idn.keySet().stream();
	}
	
	@Override
	public IntStream getElementNodes(Integer ide) {
		return ide == null ? null : this.idn2ide.getKeys(ide).stream().mapToInt(Integer::intValue);
	}

	@Override
	public Stream<N> getElementNodeNames(Integer ide) {
		return ide == null ? null : getElementNodes(ide).mapToObj(this::getNodeName);
	}

	@Override
	public IntStream getNodeElements(Integer idn) {
		return idn == null ? null : this.idn2ide.getAll(idn).stream().mapToInt(Integer::intValue);
	}

	@Override
	public Stream<E> getNodeElementNames(Integer idn) {
		return idn == null ? null : getNodeElements(idn).mapToObj(this::getElementName);
	}

	@Override
	public Stream<Ei> getNodeElementInstances(Integer idn) {
		return idn == null ? null : getNodeElements(idn).mapToObj(this::getElementInstance);
	}
	
	@Override
	public Integer getNodeId(N nodeName) {
		return this.node2idn.get(nodeName);
	}
	
	@Override
	public Integer getElementId(E elementName) {
		return this.element2ide.get(elementName);
	}
	
	public Ni getElementNetwork(Integer ide) {
		return ide == null ? null : this.ide2network.get(ide);
	}
	
	public Ni getElementNetwork(E elementName) {
		return getElementNetwork(getElementId(elementName));
	}
	
	public Stream<Ni> getNetworks() {
		return this.ide2network.values().stream().distinct();
	}
	
}
